// 造课：月将支 + 占时支 + 日干 + 日支 → 四课 + 发用（九宗门）
function 课盘(将, 时, 日干, 日支) {
  var M = L.zhiIdx(将), T = L.zhiIdx(时);
  var pan = L.buildPan(M, T);
  var 寄 = L.JIGONG[日干];
  var k = L.siKe(寄, 日支, pan.天盘);
  return { 课: k, 天盘: pan.天盘, fy: L.faYong(k, 日干, 日支, 寄, pan.天盘, GAN_Y[日干], M, T), 寄: 寄 };
}
function 三传等于(name, 将, 时, 日干, 日支, 期望, 课体关键字) {
  var r = 课盘(将, 时, 日干, 日支);
  var got = r.fy.三传.join('');
  ok(name + ' → 三传 ' + 期望, got === 期望, '实得 ' + got + '（' + r.fy.方法 + '）四课=' + r.课.map(function (x) { return x.上 + '/' + x.位; }).join(' '));
  if (课体关键字) ok(name + ' 课体含「' + 课体关键字 + '」', r.fy.方法.indexOf(课体关键字) >= 0, r.fy.方法);
  return r;
}

