/**
 * modules/CoreModule/__tests__/xiaocheng.test.js —— 小成图（霍斐然）自测
 * 结构：A 报数起卦（含外部算例 1136/5596）／B 1136 装图逐宫（外部锁死）／C 归藏自洽／D 互卦／E 取用神应期／F 阴阳得配／G 守门
 * 守零臆造：1136 逐宫与卦无忧外部算例核对；中宫「巽/震」转载矛盾以异或自洽为准（缺口②）。
 */
var X = require('../xiaocheng.js');
var ICE = require('../iching.js');
var passed = 0, failed = 0;
function ok(name, cond, detail) { if (cond) { passed++; console.log('  ✓', name); } else { failed++; console.log('  ✗', name, detail || ''); } }

// ===== A. 报数起卦（天地数表 + 外部算例）=====
console.log('A. 报数起卦（1136/5596 外部算例）');
var a1 = X.报数起('1136');
ok('1136 → 本乾乾 之艮离（乾为天 之 山火贲）', a1.本上 === '乾' && a1.本下 === '乾' && a1.之上 === '艮' && a1.之下 === '离', JSON.stringify(a1));
var a2 = X.报数起('5596');
ok('5596 → 本坎坎 之乾离（坎为水 之 天火同人）', a2.本上 === '坎' && a2.本下 === '坎' && a2.之上 === '乾' && a2.之下 === '离', JSON.stringify(a2));
ok('天地数 9→乾、10→坤（重出）', X.TIANDI[9] === '乾' && X.TIANDI[10] === '坤');
ok('天地数 奇阳偶阴：3艮(阳·艮三爻[001])、6离(阴·离三爻[101])', ICE.BAGUA[X.名To号('艮')].爻.join('') === '001' && ICE.BAGUA[X.名To号('离')].爻.join('') === '101');

// ===== B. 1136 装图逐宫（外部算例锁死）=====
console.log('B. 1136 装图逐宫（卦无忧外部算例）');
var c = X.图({ 数字: '1136' });
ok('四正 9乾/1乾/3艮/7离', c.四正[9] === '乾' && c.四正[1] === '乾' && c.四正[3] === '艮' && c.四正[7] === '离', JSON.stringify(c.四正));
ok('四隅（霍老）4乾/2乾/8震/6坎', c.四隅[4] === '乾' && c.四隅[2] === '乾' && c.四隅[8] === '震' && c.四隅[6] === '坎', JSON.stringify(c.四隅));
ok('互卦 本=乾乾、之=上互震下互坎', c.互卦.本上互 === '乾' && c.互卦.本下互 === '乾' && c.互卦.之上互 === '震' && c.互卦.之下互 === '坎', JSON.stringify(c.互卦));
ok('中宫 = 震（异或自洽；转载标题误写巽，见缺口②）', c.中宫.中宫 === '震', '实得 ' + c.中宫.中宫);
ok('中宫推演 本归藏坤·之归藏震', c.中宫.本归藏 === '坤' && c.中宫.之归藏 === '震', JSON.stringify(c.中宫));

// ===== C. 归藏自洽（同阴异阳 = 逐位异或）=====
console.log('C. 归藏自洽');
ok('guiCang(乾,乾)=坤（全同得阴）', X.guiCang('乾', '乾') === '坤');
ok('guiCang(艮,离)=震（[001]⊕[101]=[100]）', X.guiCang('艮', '离') === '震');
ok('guiCang(坎,坎)=坤（[010]⊕[010]=[000]）', X.guiCang('坎', '坎') === '坤');
ok('结合律：四正连归藏（乾⊕乾⊕艮⊕离）= (本归藏)⊕(之归藏) = 中宫震',
  X.guiCang(X.guiCang(X.guiCang('乾', '乾'), '艮'), '离') === X.guiCang(X.guiCang('乾', '乾'), X.guiCang('艮', '离'))
  && X.guiCang(X.guiCang('乾', '乾'), X.guiCang('艮', '离')) === '震');
// 八组逐位异或穷举（归藏恒为合法单卦）
var GUA8 = ['乾', '兑', '离', '震', '巽', '坎', '艮', '坤'];
var bad = 0;
for (var i = 0; i < 8; i++) for (var j = 0; j < 8; j++) if (GUA8.indexOf(X.guiCang(GUA8[i], GUA8[j])) < 0) bad++;
ok('64 组归藏恒为合法单卦', bad === 0, '异常 ' + bad);

// ===== D. 互卦（《周易》通用：2·3·4 为下互、3·4·5 为上互）=====
console.log('D. 互卦');
var hg = X.互卦('艮', '离');   // 山火贲：上互震、下互坎
ok('山火贲 互 = 上震下坎', hg.上互 === '震' && hg.下互 === '坎', JSON.stringify(hg));
var hg2 = X.互卦('乾', '乾');   // 乾为天：互 = 上下皆乾
ok('乾为天 互 = 上下皆乾', hg2.上互 === '乾' && hg2.下互 === '乾', JSON.stringify(hg2));

// ===== E. 取用神 + 应期（宫位表）=====
console.log('E. 取用神 + 应期');
ok('问财 → 巽（进退财帛·三四月）', X.图({ 数字: '1136', 问: '财' }).用神宫.join('') === '巽');
ok('问官 → 乾（事业功名·九十月）', X.图({ 数字: '1136', 问: '官' }).用神宫.join('') === '乾');
ok('问婚 → 巽/震（男巽·女震）', X.图({ 数字: '1136', 问: '婚' }).用神宫.join('/') === '巽/震');
ok('问行 → 震（行人·二月）', X.图({ 数字: '5596', 问: '行' }).用神宫.join('') === '震');
ok('问病 → 坎（病·十一月）', X.图({ 数字: '5596', 问: '病' }).用神宫.join('') === '坎');
ok('无关键词 → 不取用神（用神宫 null）', X.图({ 数字: '1136' }).用神宫 === null);

// ===== F. 阴阳得配（结构定位，不硬下吉凶）=====
console.log('F. 阴阳得配（唯坎主降·独离主升 之外的常阴阳）');
var F1 = X.GUA_YIN;
ok('八卦阴阳：乾震坎艮阳、坤巽离兑阴', F1.乾 === '阳' && F1.震 === '阳' && F1.坎 === '阳' && F1.艮 === '阳' && F1.坤 === '阴' && F1.巽 === '阴' && F1.离 === '阴' && F1.兑 === '阴');
var fc = X.图({ 数字: '1136', 问: '财' }).用神落.filter(Boolean);
ok('财(巽4)落乾：乾阳×巽阴=得配（阴阳异）', fc.length === 1 && fc[0].得配.indexOf('得配') >= 0, fc.length ? fc[0].落卦 + '/' + fc[0].宫本位 + ' ' + fc[0].得配 : '无');

// ===== G. 守门 + 切段安全 =====
console.log('G. 守门 + 无中文分号');
ok('缺料 → err', X.图({}).err !== undefined);
ok('3 位报数 → err', X.报数起('12').err !== undefined);
ok('直接给单卦 起法正确', X.图({ 本上: '离', 本下: '坤', 之上: '巽', 之下: '震' }).起法 === '直接给单卦');
ok('缺口文案逐条无中文分号（只按 ①②③ 断行，不引「；」）', X.图({ 数字: '1136', 问: '财' }).缺口.indexOf('；') < 0);
ok('输出体 JSON 无「；」（切段安全）', JSON.stringify(X.图({ 数字: '1136', 问: '财' })).indexOf('；') < 0);

console.log('\n=== 小成图 xiaocheng 自测：' + passed + ' 通过 / ' + failed + ' 失败 ===');
