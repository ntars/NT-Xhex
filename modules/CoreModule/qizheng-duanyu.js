  /** 查十一曜星性 */
  function yaoOf(name) {
    var n = normYao(name);
    if (!n) return null;
    for (var i = 0; i < YAO11.length; i++) if (YAO11[i].曜 === n) return YAO11[i];
    return null;
  }

