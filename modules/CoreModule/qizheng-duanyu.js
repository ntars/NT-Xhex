  function strip(s) { return String(s == null ? '' : s).replace(/^[\s　]+|[\s　]+$/g, ''); }

  /** 曜名规范（吃简称：日→太阳、罗→罗睺、孛→月孛、计→计都、炁→紫炁） */
  var ALIAS = {};
