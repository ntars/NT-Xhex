  var WX_RING = '木火土金水';
  function wxIdx(w) { return WX_RING.indexOf(w); }
  function shengOf(w) { return wxIdx(w) < 0 ? null : WX_RING.charAt(mod(wxIdx(w) + 1, 5)); }
  function keOf(w) { return wxIdx(w) < 0 ? null : WX_RING.charAt(mod(wxIdx(w) + 2, 5)); }
