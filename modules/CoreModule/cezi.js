  var SHENG = { 木: '火', 火: '土', 土: '金', 金: '水', 水: '木' };
  var KE = { 木: '土', 土: '水', 水: '火', 火: '金', 金: '木' };
  function relBetween(a, b) {
    if (a === b) return '比和';
    if (SHENG[a] === b) return a + '生' + b;
    if (SHENG[b] === a) return b + '生' + a;
    if (KE[a] === b) return a + '克' + b;
    if (KE[b] === a) return b + '克' + a;
    return '无关';
  }

