  // 数理五行（笔画尾数，标准姓名学惯例）
  function wxOfTail(n) {
    var t = Math.abs(n) % 10;
    if (t === 1 || t === 2) return '木';
    if (t === 3 || t === 4) return '火';
    if (t === 5 || t === 6) return '土';
    if (t === 7 || t === 8) return '金';
    return '水'; // 9, 0
  }
