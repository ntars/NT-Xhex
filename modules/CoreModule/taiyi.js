/**
 * modules/CoreModule/taiyi.js —— 太乙神数内核 C17【单一真源 · 适配层】
 *
 * 算什么：某年（岁计）太乙局 —— 太乙积年 · 入局数 · 五元六纪 · 阴阳遁 · 十六神 · 天目(文昌) ·
 *         计神 · 客目(始击) · 太乙落宫（含主客算框架）。
 *
 * 算法来源（有权威用权威，零臆造；多源核对一致）：
 *   · 太乙积年：据《太乙金镜式经》载「上混沌甲子之岁至唐开元十二年(724年)有 1937281 积年」。
 *       故 积年(Y) = 1937281 + (Y − 724)。（注：太乙另有「上元 10153917」等多套积年体系，本内核
 *       采用《金镜式经》明文 724 年基点这一公认口径；不同上元仅平移整数，不影响局数/十六神相对排布。）
 *   · 五元六纪周期：五元(甲/丙/戊/庚/壬子元，每元72年)六纪(每纪60年) = 360 年为一周期。
 *       入纪元数 = 积年 % 360；入局数 = 入纪元数 % 72（即 积年 % 72，1–72）。（《金镜式经》入局法逐字一致。）
 *   · 元序/阴阳遁：元序 = floor(积年 % 360 / 72)：0甲子(阳)/1丙子(阴)/2戊子(阳)/3庚子(阴)/4壬子(阳)。
 *       阳遁 = 甲戊壬元，阴遁 = 丙庚元。
 *   · 十六神（固定顺布，5 源逐字一致）：子地主、丑阳德、艮和德、寅吕申、卯高丛、辰太阳、巽大旲、
 *       巳大神、午大威、未天道、坤大武、申武德、酉太簇、戌阴主、乾阴德、亥大义。（各神主事见 SHEN16。）
 *   · 天目(文昌)：将入局数 以 18 累除，不及 18 之余数 r；阳遁自「武德(申)」起顺行十六神、至乾坤重留一次，
 *       阴遁自「吕申(寅)」起顺行、至艮巽重留一次，数到 r 处为天目。（《金镜式经》例：入局71→阳遁大武坤/阴遁和德艮，本内核核验一致。）
 *   · 计神：阳遁起吕申寅、阴遁起申，顺行十二支；计神位即其所在地支（作为始击偏移基准）。（《金镜式经》）
 *   · 客目(始击)：以计神加于「和德(艮)」上、顺行十六神，所得位为始击。（《金镜式经》）
 *
 * 缺口（严守零臆造，核到权威源才补；以下项不同流派公式分歧明显，本内核不假报已锁）：
 *   ① 太乙落宫（太乙神所临八宫 1/2/3/4/6/7/8/9，不入中五）的「每几年移一宫」有 3 年/9 年等异说，
 *       本内核取「每 9 局(年)移一宫、阳遁自乾顺/阴遁自巽逆」主流近似，标【待黄金盘验证】。
 *   ② 主客算/主客胜负、阳九百六之灾期、及 太乙 与 三才/八将 的精确推演，不同家传口径差异大，
 *       本内核仅给出 十六神/文昌/计神/始击 这「二目二神」确定性框架，主客算留接口待裁定。
 *
 * 加载：UMD —— require（无外部依赖，纯规则）；浏览器挂 NT.core.taiyi。
 * 校验：modules/CoreModule/__tests__/taiyi.test.js（积年/入局/十六神/天目例 确定性断言）。
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else { root.NT = root.NT || {}; root.NT.core = root.NT.core || {}; root.NT.core.taiyi = factory(); }
})(typeof self !== 'undefined' ? self : this, function () {

  // 十二支序
  var ZHI = '子丑寅卯辰巳午未申酉戌亥';
  // 十六神固定顺布（IDX 0..15），名+主事（5 源一致）
  var SHEN16 = [
    { 名: '地主', 神: '子', 主: '动摇言语事' }, { 名: '阳德', 神: '丑', 主: '施恩育物事' },
    { 名: '和德', 神: '艮', 主: '和集成就事' }, { 名: '吕申', 神: '寅', 主: '运用主宰事' },
    { 名: '高丛', 神: '卯', 主: '发挥事' }, { 名: '太阳', 神: '辰', 主: '危会兵曳事' },
    { 名: '大旲', 神: '巽', 主: '申命号令事' }, { 名: '大神', 神: '巳', 主: '毁拆破废事' },
    { 名: '大威', 神: '午', 主: '光明威烈事' }, { 名: '天道', 神: '未', 主: '阴私事' },
    { 名: '大武', 神: '坤', 主: '刑罚事' }, { 名: '武德', 神: '申', 主: '传送迁移事' },
    { 名: '太簇', 神: '酉', 主: '更易肃杀事' }, { 名: '阴主', 神: '戌', 主: '危期兵丧事' },
    { 名: '阴德', 神: '乾', 主: '命令事' }, { 名: '大义', 神: '亥', 主: '计谋废弃事' }
  ];
  // 八宫（太乙不入中五）：序 1乾 2离 3艮 4震 6兑 7坤 8坎 9巽
  var BAGUA8 = [1, 2, 3, 4, 6, 7, 8, 9];

  // ===== 太乙积年（《金镜式经》724年基点 1937281）=====
  function jinian(y) { return 1937281 + (y - 724); }

  // ===== 入局数 / 元序 / 阴阳遁 =====
  function ruju(y) {
    var n = jinian(y);
    var 入纪元数 = ((n % 360) + 360) % 360;
    var 入局数 = ((入纪元数 % 72) + 72) % 72; if (入局数 === 0) 入局数 = 72;
    var 元序 = Math.floor(入纪元数 / 72) % 5; // 0甲子/1丙子/2戊子/3庚子/4壬子
    var 阴 = (元序 === 1 || 元序 === 3);       // 丙/庚元为阴遁
    return { 积年: n, 入纪元数: 入纪元数, 入局数: 入局数, 元序: 元序, 元名: ['甲子', '丙子', '戊子', '庚子', '壬子'][元序], 阴阳: 阴 ? '阴' : '阳', 阴: 阴 };
  }

  // ===== 天目(文昌)：入局 % 18 余数 r（1..18），阳遁自武德(申=IDX11)起、阴遁自吕申(寅=IDX3)起，顺行十六神；
  //       阳遁 乾坤重留一次、阴遁 艮巽重留一次（每重留神计 2 步）。数到 r 步处为天目。
  function tianmu(入局, 阴) {
    var r = ((入局 % 18) + 18) % 18; if (r === 0) r = 18;
    var start = 阴 ? 3 : 11;                 // 阴遁吕申(寅=IDX3)、阳遁武德(申=IDX11)
    var 重留 = 阴 ? [2, 6] : [10, 14];       // 阴遁 艮(IDX2)/巽(IDX6)、阳遁 坤(IDX10)/乾(IDX14)
    var pos = start, count = 0;
    while (true) {
      count++;
      if (count === r) return SHEN16[pos];
      if (重留.indexOf(pos) >= 0) { count++; if (count === r) return SHEN16[pos]; }
      pos = (pos + 1) % 16;
    }
  }

  // ===== 计神：阳遁起吕申寅(寅)、阴遁起申，顺行十二支；返回所在地支 + 自起点步数 =====
  function jishen(入局, 阴) {
    var start = 阴 ? ZHI.indexOf('申') : ZHI.indexOf('寅'); // 阴遁申、阳遁寅
    var 步 = ((入局 - 1) % 12 + 12) % 12; // 顺行十二支，每局一步
    var 支 = ZHI[(start + 步) % 12];
    return { 地支: 支, 步: 步 };
  }

  // ===== 客目(始击)：以计神加于「和德(艮=IDX2)」顺行十六神，走「计神步数」步所临之神 =====
  function shiji(入局, 阴) {
    var js = jishen(入局, 阴);
    var pos = 2; // 和德(艮) = IDX2
    for (var i = 0; i < js.步; i++) pos = (pos + 1) % 16;
    return { 十六神: SHEN16[pos].名, 计神地支: js.地支 };
  }

  // ===== 太乙落宫（主流近似：每 9 局(年)移一宫，阳遁自乾1顺 / 阴遁自巽9逆；【待黄金盘验证】）=====
  function taiyiPalace(入局, 阴) {
    var idx = Math.floor(((入局 - 1) % 72) / 9) % 8; // 0..7
    return 阴 ? BAGUA8[(8 - 1 - idx + 8) % 8] : BAGUA8[idx];
  }

  /**
   * 太乙岁计起局。
   * @param {Object} inp { y }  公元年（AD）
   * @returns 完整太乙岁计局。
   */
  function chart(inp) {
    inp = inp || {};
    var y = inp.y;
    if (!y) return { err: '太乙岁计需公元年，例如「太乙 2026」或「2026年太乙局」。' };
    var rj = ruju(y);
    var tm = tianmu(rj.入局数, rj.阴);
    var js = jishen(rj.入局数, rj.阴);
    var sj = shiji(rj.入局数, rj.阴);
    var pal = taiyiPalace(rj.入局数, rj.阴);
    return {
      年: y,
      积年: rj.积年,
      入局数: rj.入局数, 入纪元数: rj.入纪元数,
      元: rj.元名 + '元', 阴阳遁: rj.阴阳,
      十六神序: SHEN16.map(function (s) { return s.名; }),
      天目文昌: tm.名 + '(' + tm.神 + '·' + tm.主 + ')',
      计神: js.地支 + '（自' + (rj.阴 ? '申' : '寅') + '顺行第' + (js.步 + 1) + '支）',
      客目始击: sj.十六神 + '（计神' + sj.计神地支 + '加和德顺行）',
      太乙落宫: pal + '宫【待黄金盘验证·落宫移宫年限异说】',
      缺料: '太乙落宫「每几年移一宫」(3年/9年异说) 与 主客算/阳九百六 不同流派公式分歧大，本内核仅确定性输出二目二神(文昌/计神/始击/十六神)，落宫与主客算标【待黄金盘验证】。'
    };
  }

  return {
    chart: chart, jinian: jinian, ruju: ruju, tianmu: tianmu, jishen: jishen, shiji: shiji,
    taiyiPalace: taiyiPalace, SHEN16: SHEN16
  };
});
